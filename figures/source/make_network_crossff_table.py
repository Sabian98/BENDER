"""Supplementary table: contact-network properties under CALVADOS-2 and MPIPI-GG.

Both force fields use the same protocol (contact graphs with C-alpha distance
below 0.8 nm and |i-j| >= 3 on about 50 evenly spaced production frames,
frame means; MPIPI-GG coordinates unwrapped first). Every paired sequence in
the six BENDER groups is used, none excluded.

"Length removed": each force field's values are regressed on ln N and
(ln N)^2 by least squares and the residuals are correlated.

Inputs:
  BENDER-BIO/BENDER_BIO.csv                               (CALVADOS-2)
  BENDER-BIO/MPIPI/MPIPI Results/mpipi_results_v2.csv      (MPIPI-GG, in_paper_set)
Output:
  build/network_crossff_table.tex
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats
import bender_paths as paths  # noqa: E402  (data and output locations: paths.py at the repository root)

HERE = Path(__file__).resolve().parent
BIO = paths.BIO
MPIPI = paths.GG_RESULTS
OUT = paths.out("si", "network_crossff_table.tex")   # the MPIPI-GG block of the SI network table

FEATURES = [("fragmentation_index", "Fragmentation index"),
            ("global_efficiency", r"Global efficiency $g_\text{eff}$"),
            ("avg_clustering", "Average clustering"),
            ("transitivity", "Transitivity"),
            ("degree_assortativity", "Degree assortativity")]
LINEAGES = ["Mammals", "Fungi", "Plants", "Protists", "Bacteria", "Viruses"]


def length_residuals(y, n):
    X = np.column_stack([np.ones_like(n), np.log(n), np.log(n) ** 2])
    coef, *_ = np.linalg.lstsq(X, y, rcond=None)
    return y - X @ coef


def fmt(x, d=3):
    return f"{x:.{d}f}".replace("-", "$-$")


def main():
    bio = pd.read_csv(BIO, low_memory=False).set_index("UniProt_ID")
    mp = pd.read_csv(MPIPI).set_index("UniProt_ID")
    mp = mp[(mp["status"] == "ok") & mp["in_paper_set"]]
    mp = mp[mp.index.isin(bio.index)]                                   # 35 paper-set pairs were non-mammal animals, dropped from BENDER
    mp = mp[bio.loc[mp.index, "kingdom"].isin(LINEAGES).to_numpy()]   # the six BENDER groups
    print("paired sequences in the six groups:", len(mp))
    cal = bio.loc[mp.index]
    n = mp["n_residues"].to_numpy(float)
    assert (n == cal["length"].to_numpy()).all()
    kingdom = cal["kingdom"]

    rows, summary = [], {}
    for col, label in FEATURES:
        x, y = cal[col].to_numpy(), mp[col].to_numpy()
        r = stats.pearsonr(x, y)[0]
        rho = stats.spearmanr(x, y)[0]
        r_len = stats.pearsonr(length_residuals(x, n), length_residuals(y, n))[0]
        by_lin = [stats.pearsonr(x[(kingdom == g).to_numpy()], y[(kingdom == g).to_numpy()])[0]
                  for g in LINEAGES]
        summary[col] = dict(r=r, r_len=r_len, lo=min(by_lin), hi=max(by_lin),
                            weakest=LINEAGES[int(np.argmin(by_lin))])
        rows.append(f"{label} & {fmt(np.median(x))} & {fmt(np.median(y))} & {fmt(r, 2)} & "
                    f"{fmt(rho, 2)} & {fmt(r_len, 2)} & {fmt(min(by_lin), 2)}--{fmt(max(by_lin), 2)} \\\\")
        print(f"{col:22s} median {np.median(x):.4f} / {np.median(y):.4f}  r {r:.3f}  rho {rho:.3f}  "
              f"r_len {r_len:.3f}  lineages {min(by_lin):.3f}-{max(by_lin):.3f} (weakest {summary[col]['weakest']})")

    body = "\n".join(rows)
    tex = rf"""% Generated by figures/source/make_network_crossff_table.py; do not edit by hand.
\begin{{table}}[htbp]
\centering
\caption{{Contact-network properties of the {len(mp):,} sequences simulated with both
force fields. Both use the same protocol: contact graphs with
$C_\alpha$--$C_\alpha$ distance below 0.8\,nm and $|i - j| \geq 3$ on about
50 evenly spaced production frames, averaged over frames; MPIPI-GG
coordinates are unwrapped from minimum-image bond vectors first. $r$ and
$\rho$, Pearson and Spearman correlations between force fields; length
removed, Pearson $r$ between the residuals of each force field's values after
least-squares regression on $\ln N$ and $(\ln N)^2$; by group, range of $r$
over the six groups. No sequence is excluded.}}
\label{{tab:network_crossff}}
\footnotesize
\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{lrrrrrr}}
\toprule
 & \multicolumn{{2}}{{c}}{{Median}} & & & & \\
\cmidrule(lr){{2-3}}
Property & CALVADOS-2 & MPIPI-GG & $r$ & $\rho$ & $r$, length removed & $r$ by group \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    OUT.write_text(tex)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
