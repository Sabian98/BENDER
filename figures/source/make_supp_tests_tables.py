"""SI tables for the parameter swap and the hnRNPA1 LCD variants (2026-10-22), written to output/si/
(swap_results.tex, bremer_table.tex) from data/controls/ (analyze_jctc_runs.py) and simulations/inputs/.
CALVADOS-2 cells of the variant table stay blank until those runs are analyzed."""
from pathlib import Path

import numpy as np
import pandas as pd
import bender_paths as paths  # noqa: E402  (data and output locations: paths.py at the repository root)

HERE = Path(__file__).resolve().parent
DATA, INPUTS = paths.CONTROLS, paths.INPUTS
SETS = [("contested", "Contested"), ("aliph_rich", "Aliphatic-rich"), ("his_rich", "His-rich"), ("control", "Control")]
SWAPS = [("aro", "Arg/Aromatic pairs"), ("aliph", "Aliphatic pairs"), ("his", "His charge"), ("all", "All three")]


def run(ff, name):
    p = DATA / f"{ff}_{name}.csv"
    if not p.exists():
        return pd.DataFrame(columns=["nu", "rg", "sequence"])
    d = pd.read_csv(p).drop_duplicates("id", keep="last")
    return d[d.status == "ok"].set_index("id")


def ci(x, seed=0):
    x = np.asarray(x, float)
    return np.percentile(np.random.default_rng(seed).choice(x, (4000, len(x))).mean(1), [2.5, 97.5])


ref = pd.read_csv(INPUTS / "swap_set_300K.tsv", sep="\t").set_index("UniProt_ID")
sw = {k: run("recharged", f"swap_{k}")["nu"] for k, _ in SWAPS}
nohis = ref.index[ref.f_H == 0]
rep = (sw["his"].reindex(nohis) - ref.nu_recharged.reindex(nohis)).dropna()
lo, hi = ci(rep)
L = [r"""\begin{table}[H]
  \centering
  \caption{Mean $\Delta\nu$ (MPIPI-Recharged minus CALVADOS-2) of each sequence set in the parameter swap, unswapped
  and with each swap, together with the mean shift in $\nu$ caused by the swap, its 95\% bootstrap interval over
  chains, and the share of chains with $|\Delta\nu| > 0.05$ (unswapped / swapped). Replicate runs with unchanged potentials (the """
     + f"{len(rep)}" + r""" Histidine-free chains under the Histidine swap) differ by """ + f"{rep.std():.3f}"
     + r""" per chain and by """ + f"${rep.mean():+.3f}$ (95\\% interval ${lo:+.3f}$ to ${hi:+.3f}$)" + r""" on average.}
  \label{tab:swap_results}
  \small
  \begin{tabular}{llrrrcc}
    \toprule
    Swap & Set & $n$ & $\langle\Delta\nu\rangle$ before & after & shift in $\nu$ (95\% interval) & $|\Delta\nu| > 0.05$ \\
    \midrule"""]
for i, (k, klab) in enumerate(SWAPS):
    for j, (g, glab) in enumerate(SETS):
        idx = ref.index[ref.set == g]
        idx = idx[sw[k].reindex(idx).notna().to_numpy()]      # chains with a swap run, so every column uses the same chains
        before = ref.loc[idx, "dnu_recharged_minus_c2"]
        after = sw[k].reindex(idx) - ref.loc[idx, "nu_calvados2"]
        shift = (sw[k].reindex(idx) - ref.loc[idx, "nu_recharged"]).dropna()
        a, b = ci(shift, seed=i * 4 + j)
        L.append(f"    {klab if j == 0 else ''} & {glab} & {len(shift)} & ${before.mean():+.3f}$ & ${after.mean():+.3f}$ & "
                 f"${shift.mean():+.3f}$ (${a:+.3f}$, ${b:+.3f}$) & {100 * (before.abs() > 0.05).mean():.0f}\\% / "
                 f"{100 * (after.abs() > 0.05).mean():.0f}\\% \\\\")
    if i < len(SWAPS) - 1:
        L.append(r"    \midrule")
L.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")
paths.out("si", "swap_results.tex").write_text("% Generated by figures/source/make_supp_tests_tables.py; do not edit by hand.\n" + "\n".join(L))

br = pd.read_csv(INPUTS / "bremer2022_a1lcd_300K.tsv", sep="\t").set_index("run_name")
mr, c2 = run("recharged", "bremer2022"), run("calvados2", "bremer2022")
t = br.join(mr[["rg", "nu", "sequence"]].add_prefix("mr_")).join(c2[["rg", "nu"]].add_prefix("c2_"))
t = t.sort_values(["saxs_Rg_A", "construct"], na_position="last")
fmt = lambda v, f: "--" if pd.isna(v) else format(v, f)  # noqa: E731
B = [r"""\begin{table}[H]
  \centering
  \caption{The 38 hnRNPA1 LCD variants of Bremer et al.\cite{bremer_deciphering_2022} (137 residues), with the SAXS
  radius of gyration and apparent scaling exponent where measured and the simulated radius of gyration and $\nu$ in
  both force fields. All measured variants except A1-LCD+NLS are in the radius-of-gyration training set of
  CALVADOS-2, with the same experimental values.\cite{tesei_improved_2023} """ + (r"\placeholder{CALVADOS-2 runs still being completed, with " + f"{len(c2)} of 38" + r" so far.}" if len(c2) < 38 else "") + r"""}
  \label{tab:bremer}
  \footnotesize
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{lrrrrrrrrrr}
    \toprule
     & & & & & \multicolumn{2}{c}{SAXS} & \multicolumn{2}{c}{MPIPI-Recharged} & \multicolumn{2}{c}{CALVADOS-2} \\
    \cmidrule(lr){6-7}\cmidrule(lr){8-9}\cmidrule(lr){10-11}
    Variant & R & K & F+W+Y & D+E & $R_g$ (\AA) & $\nu_\mathrm{app}$ & $R_g$ (\AA) & $\nu$ & $R_g$ (\AA) & $\nu$ \\
    \midrule"""]
for r in t.itertuples():
    q = r.mr_sequence if isinstance(r.mr_sequence, str) else ""
    cnt = lambda aa: str(sum(q.count(a) for a in aa)) if q else "--"  # noqa: E731
    B.append(f"    {r.construct.replace('A1-LCD', 'A1-LCD')} & {cnt('R')} & {cnt('K')} & {cnt('FWY')} & {cnt('DE')} & "
             f"{fmt(r.saxs_Rg_A, '.1f')} & {fmt(r.saxs_nu_app, '.3f')} & {fmt(10 * r.mr_rg, '.1f')} & "
             f"{fmt(r.mr_nu, '.3f')} & {fmt(10 * r.c2_rg if pd.notna(r.c2_rg) else np.nan, '.1f')} & "
             f"{fmt(r.c2_nu, '.3f')} \\\\")
B.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")
paths.out("si", "bremer_table.tex").write_text("% Generated by figures/source/make_supp_tests_tables.py; do not edit by hand.\n" + "\n".join(B))
print("wrote si/swap_results.tex and si/bremer_table.tex;", len(rep), "replicate chains; CALVADOS-2 Bremer", len(c2), "of 38")
